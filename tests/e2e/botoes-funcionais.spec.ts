import { test, expect, type Page } from '@playwright/test'

const cards = (page: Page) => page.getByTestId('nft-card')

test('abas e painéis do catálogo filtram de verdade', async ({ page }) => {
  await page.goto('/')
  await expect(cards(page)).toHaveCount(6)
  // Coleção: nft-1 e nft-10 caem em "Arte digital" (classificação derivada, ver taxonomy.ts)
  await page.getByRole('button', { name: /^Arte digital/ }).click()
  await expect(page).toHaveURL(/collection=Arte/)
  await expect(cards(page)).toHaveCount(2)
  await expect(page.getByRole('button', { name: /^Arte digital/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /^Limpar filtros/ }).click()
  await expect(cards(page)).toHaveCount(6)
  // Rede
  await page.getByRole('button', { name: /^Solana/ }).click()
  await expect(cards(page)).toHaveCount(4)
  await page.getByRole('button', { name: /^Limpar filtros/ }).click()
  // Abas
  await page.getByRole('button', { name: 'Novos lançamentos' }).click()
  await expect(page).toHaveURL(/tab=novos/)
  await expect(cards(page).first()).toContainText('Last Echo')
  await page.getByRole('button', { name: 'Em alta' }).click()
  await expect(page.getByRole('button', { name: 'Em alta' })).toHaveAttribute('aria-pressed', 'true')
  await expect(cards(page)).toHaveCount(6)
  await page.getByRole('button', { name: 'Todos os NFTs' }).click()
  await expect(page).not.toHaveURL(/tab=/)
})

test('card em destaque, banners e carrossel funcionam', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: /^NFT em destaque:/ }).click()
  await expect(page).toHaveURL(/\/nfts\/nft-7$/)
  await page.goto('/')
  await page.getByRole('link', { name: /^Explorar: Arte digital selecionada/ }).click()
  await expect(page).toHaveURL(/collection=Arte/)
  await expect(cards(page)).toHaveCount(2)
  await page.goto('/')
  const dots = page.getByRole('group', { name: 'Imagens em destaque' }).getByRole('button', { name: /^Mostrar imagem/ })
  await expect(dots).toHaveCount(4)
  await dots.nth(2).click()
  await expect(dots.nth(2)).toHaveAttribute('aria-current', 'true')
  await expect(dots.nth(0)).not.toHaveAttribute('aria-current', 'true')
  const pause = page.getByRole('button', { name: /rotação/ })
  await pause.click()
  await expect(pause).toHaveAttribute('aria-pressed', 'true')
})

test('rodapé: links reais e newsletter com validação', async ({ page }) => {
  await page.goto('/')
  const footer = page.locator('footer')
  expect(await footer.locator('a[href="#"], a:not([href])').count()).toBe(0)
  await footer.getByRole('link', { name: 'Como comprar NFTs' }).click()
  await expect(page).toHaveURL(/\/aprenda\/como-funciona-a-propriedade-de-nfts$/)
  await footer.getByRole('link', { name: 'Fotografia' }).click()
  await expect(page).toHaveURL(/collection=Fotografia/)
  const social = footer.getByRole('link', { name: /Instagram/ })
  await expect(social).toHaveAttribute('rel', 'noopener noreferrer')
  await expect(social).toHaveAttribute('target', '_blank')
  const input = footer.getByLabel('Assinar newsletter')
  await footer.getByRole('button', { name: 'Enviar' }).click()
  await expect(footer.getByRole('alert')).toContainText('e-mail válido')
  await input.fill('ana@example.test')
  await footer.getByRole('button', { name: 'Enviar' }).click()
  await expect(footer.getByRole('status')).toContainText('Inscrição simulada')
  await expect(input).toHaveValue('')
})

test('Aplicar (faixa de preço): desabilitado sem mudança, aplica mín./máx. e limpa com campos vazios', async ({ page }) => {
  await page.goto('/')
  await expect(cards(page)).toHaveCount(6)
  const apply = page.getByRole('button', { name: 'Aplicar' })
  await expect(apply).toBeDisabled()
  await page.getByLabel('Preço mín. (ETH)').fill('1')
  await expect(apply).toBeEnabled()
  await apply.click()
  await expect(page).toHaveURL(/min=/)
  await expect(page.getByTestId('page-indicator')).toBeVisible()
  await expect(cards(page).first()).not.toContainText('Aurora Genesis')
  await expect(apply).toBeDisabled()
  await page.getByLabel('Preço mín. (ETH)').fill('')
  await expect(apply).toBeEnabled()
  await apply.click()
  await expect(page).not.toHaveURL(/min=/)
  await expect(cards(page)).toHaveCount(6)
})
